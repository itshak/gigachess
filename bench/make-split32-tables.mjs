import {writeFileSync} from 'node:fs';
import {gzipSync} from 'node:zlib';
import {_naive} from '../dist/attacks.js';
import './make-half-rook-tables.mjs';
let rng=0x9bbace1;
function rnd(){rng^=rng<<13;rng^=rng>>>17;rng^=rng<<5;return rng>>>0}
function subsets(mask){
 let x=0;const arr=[];do{arr.push(x>>>0);x=(x-mask)&mask}while(x!==0);return arr;
}
const cache=new Map();
function find(mask){
 if(cache.has(mask))return cache.get(mask);
 const subs=subsets(mask),bits=Math.log2(subs.length);
 if(bits===0)return {m:0,shift:0,bits:0,subs,idx:[0]};
 for(let extra=0;extra<=3;extra++){
  const n=bits+extra,shift=32-n,seen=new Uint32Array(1<<n);let serial=0;
  const limit=extra===0?300000:extra===1?120000:30000;
  for(let i=0;i<limit;i++){
   let m=i%4===0?rnd():i%4===1?rnd()&rnd():rnd()&rnd()&rnd();
   serial++;
   let ok=true;
   for(const x of subs){const k=Math.imul(x,m)>>>shift;if(seen[k]===serial){ok=false;break}seen[k]=serial}
   if(ok){const result={m:m>>>0,shift,bits:n,subs,idx:subs.map(x=>Math.imul(x,m)>>>shift)};cache.set(mask,result);return result}
  }
 }
 throw Error('no perfect hash '+mask);
}
function relevantMask(s,dirs){
 let lo=0,hi=0;
 for(const [df,dr] of dirs){
  let f=(s&7)+df,r=(s>>3)+dr;
  while(f>=0&&f<8&&r>=0&&r<8&&f+df>=0&&f+df<8&&r+dr>=0&&r+dr<8){
   const t=r*8+f;if(t<32)lo|=1<<t;else hi|=1<<(t-32);f+=df;r+=dr;
  }
 }
 return [lo>>>0,hi>>>0];
}
for(const [role,dirs,fn] of [
 ['rook',[[1,0],[-1,0],[0,1],[0,-1]],_naive.rookAttacksNaive],
 ['bishop',[[1,1],[-1,1],[1,-1],[-1,-1]],_naive.bishopAttacksNaive]
]){
 const meta=new Uint32Array(64*8),blocks=[];let off=0,used=0;
 for(let sq=0;sq<64;sq++){
  const [ml,mh]=relevantMask(sq,dirs),l=find(ml),h=find(mh),size=1<<(l.bits+h.bits);
  if(role==='rook')continue; // Preserve deterministic bishop search sequence.
  const t=new Uint32Array(size*2);
  meta.set([ml,mh,l.m,h.m,l.shift,h.shift,h.bits,off],sq*8);
  for(let i=0;i<l.subs.length;i++)for(let j=0;j<h.subs.length;j++){
   const idx=((l.idx[i]<<h.bits)|h.idx[j])*2;
   const att=fn(sq,{lo:l.subs[i],hi:h.subs[j]});t[idx]=att.lo;t[idx+1]=att.hi;used++;
  }
  blocks.push(Buffer.from(t.buffer));off+=size;
 }
 if(role==='rook')continue;
 const data=Buffer.concat([Buffer.from(meta.buffer),...blocks]),gz=gzipSync(data,{level:9});
 // RFC 1952 OS identifier: canonicalize to the existing Unix value.
 // Windows emits a different header byte despite identical deflate data.
 gz[9]=3;
 if(role==='bishop')writeFileSync('src/'+role+'Split32Blob.ts','// Generated by bench/make-split32-tables.mjs\nexport const '+role+'Split32Blob = "'+gz.toString('base64')+'";\n');
 if(role==='bishop')console.log({role,entries:off,used,bytes:data.length,gzip:gz.length});
}
